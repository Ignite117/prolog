% =====================================================================
%  ЛАБОРАТОРНАЯ РАБОТА № 3
%  Динамическое управление фактами. Задачи планирования.
%  Глава 7.3 — Ханойские башни (с. 168)
%
%  Три штыря и N дисков. Все диски вначале на левом штыре, нужно
%  перенести их на средний, пользуясь правым как запасным.
%  Переносить можно только верхний диск, и нельзя класть больший
%  диск на меньший.
%
%  Стратегия (книга, с. 168):
%    - граничное условие: на исходном штыре нет дисков — делать нечего;
%    - перенести N-1 дисков с исходного на запасной (итоговый служит
%      запасным) — рекурсивно;
%    - перенести один диск с исходного на итоговый — это и есть ход;
%    - перенести N-1 дисков с запасного на итоговый (исходный служит
%      запасным) — снова рекурсивно.
% =====================================================================

% --- Вариант из книги: ходы просто печатаются ---

ханой(N) :- переместить(N, левый, средний, правый).

% переместить(СколькоДисков, Исходный, Итоговый, Запасной)
% Отсечение '!' в граничном условии не даёт Prolog'у при возврате
% попробовать второе утверждение с N = 0 и уйти в бесконечную
% рекурсию с отрицательным числом дисков.
переместить(0, _, _, _) :- !.
переместить(N, A, B, C) :-
    M is N - 1,
    переместить(M, A, C, B),
    сообщить(A, B),
    переместить(M, C, B, A).

сообщить(X, Y) :-
    write(['переместили диск со штыря', X, 'на штырь', Y]), nl.


% --- Вариант с динамической базой данных ---
%  Та же стратегия, но ходы не печатаются, а ЗАПОМИНАЮТСЯ как факты.
%  Это и есть «динамическое управление фактами»: план строится
%  в базе данных, а потом его можно анализировать, печатать,
%  проигрывать назад и так далее.

% Объявление dynamic обязательно: без него обращение к предикату,
% у которого пока нет ни одного утверждения, вызовет ошибку
% existence_error, а не аккуратный неуспех.
:- dynamic ход/3.            % ход(Номер, Откуда, Куда)
:- dynamic счётчик_ходов/1.

% ханой_план(N) — построить план для N дисков и показать статистику.
ханой_план(N) :-
    очистить_план,
    план(N, левый, средний, правый),
    счётчик_ходов(K),
    Минимум is 2^N - 1,       % ^ даёт целое, ** в старых версиях — число с точкой
    склонение(N, [диска, дисков, дисков], СловоД),
    склонение(K, [ход, хода, ходов],      СловоХ),
    format('      план для ~w ~w построен~n', [N, СловоД]),
    format('      сделано ~w ~w, теоретический минимум 2^~w-1 = ~w~n',
           [K, СловоХ, N, Минимум]).

% retractall удаляет ВСЕ утверждения, подходящие под образец,
% и всегда завершается успехом (даже если удалять нечего).
очистить_план :-
    retractall(ход(_, _, _)),
    retractall(счётчик_ходов(_)),
    assertz(счётчик_ходов(0)).

план(0, _, _, _) :- !.
план(N, A, B, C) :-
    M is N - 1,
    план(M, A, C, B),
    записать_ход(A, B),
    план(M, C, B, A).

% Увеличить счётчик и добавить очередной ход в конец базы данных.
% retract/1 снимает старое значение счётчика, assertz/1 добавляет
% новое утверждение ПОСЛЕ всех существующих (asserta/1 добавил бы
% перед ними, и ходы пошли бы в обратном порядке).
записать_ход(A, B) :-
    retract(счётчик_ходов(K)),
    K1 is K + 1,
    assertz(счётчик_ходов(K1)),
    assertz(ход(K1, A, B)).

% показать_план — напечатать сохранённый план.
показать_план :-
    forall(ход(N, A, B),
           format('      ход ~w:~t~16| ~w -> ~w~n', [N, A, B])).

% ходы_штыря(Штырь, Список) — номера всех ходов, затронувших штырь.
% Пример анализа уже построенного плана, ради которого ходы
% и сохранялись в базе данных.
% findall/3 сначала соберёт все ходы ИЗ этого штыря, и лишь потом все
% ходы В него, поэтому номера получаются вперемешку; msort/2 наводит
% порядок, не выбрасывая повторы (обычный sort/2 их удалил бы).
ходы_штыря(Штырь, Список) :-
    findall(N, (ход(N, Штырь, _) ; ход(N, _, Штырь)), Вперемешку),
    msort(Вперемешку, Список).


лр3 :-
    заголовок('ЛР3. Ханойские башни и динамическая база данных'),
    format('  Вариант из книги, 3 диска — ходы печатаются сразу:~n'),
    ханой(3),
    nl,
    format('  Вариант с динамическими фактами, 3 диска:~n'),
    ханой_план(3),
    показать_план,
    ходы_штыря(правый, Правые),
    format('      ходы, затронувшие правый штырь: ~w~n', [Правые]),
    nl,
    format('  Рост числа ходов с числом дисков:~n'),
    forall(принадлежит(N, [1, 5, 10]), ханой_план(N)),
    nl.


% =====================================================================
%  ЛАБОРАТОРНАЯ РАБОТА № 4
%  Поиск в пространстве состояний. Алгоритм A*.
%  Глава 7.9 — Поиск по графу (с. 187)
%
%  Граф — дороги между городами Северной Англии (книга, с. 188).
%  Книга показывает поиск вглубь и поиск «первый — лучший» (с. 191-192),
%  в котором из списка путей всегда продлевается самый короткий.
%  A* — тот же приём, но вместо фактической длины пути g сравнивается
%  оценка f = g + h, где h — нижняя оценка оставшегося расстояния.
%  Если h никогда не завышает (такая оценка называется допустимой),
%  A* гарантированно находит кратчайший путь, но просматривает меньше
%  узлов, чем поиск по чистому g.
% =====================================================================

% дуга(Город1, Город2, Расстояние) — дороги и их длина в милях.
% В книге предикат называется a/3; здесь он переименован, чтобы
% латинскую 'a' нельзя было спутать с кириллической 'а'.
дуга(ньюкасл,    карлайл,    58).
дуга(карлайл,    пенрит,     23).
дуга(дарлингтон, ньюкасл,    40).
дуга(пенрит,     дарлингтон, 52).
дуга(уэркингтон, карлайл,    33).
дуга(уэркингтон, пенрит,     39).

% смежный(X, Y, D) — дороги двусторонние, поэтому каждая дуга годится
% в обе стороны. В книге то же самое записано дизъюнкцией
% (a(X,Y,Z) ; a(Y,X,Z)).
смежный(X, Y, D) :- дуга(X, Y, D).
смежный(X, Y, D) :- дуга(Y, X, D).

% координаты(Город, X, Y) — приблизительное положение города
% в условной плоской системе координат (мили, начало — Уэркингтон).
% В книге этих данных нет: они добавлены специально ради эвристики,
% так как без координат неоткуда взять оценку «по прямой».
координаты(уэркингтон,   0,   0).
координаты(карлайл,     25,  17).
координаты(пенрит,      32,   1).
координаты(ньюкасл,     77,  23).
координаты(дарлингтон,  80,  -8).

% эвристика(Узел, Цель, H) — расстояние по прямой.
% Это ДОПУСТИМАЯ оценка: по прямой всегда не длиннее, чем по дороге,
% поэтому h никогда не завышает остаток и A* не ошибётся.
% Проверить допустимость: ?- проверить_эвристику.
эвристика(Узел, Цель, H) :-
    координаты(Узел, X1, Y1),
    координаты(Цель, X2, Y2),
    H is sqrt((X1 - X2) ** 2 + (Y1 - Y2) ** 2).

% ---------------------------------------------------------------------
% Алгоритм A*
%
% Состояние поиска — список открытых узлов, каждый вида
%     узел(F, G, ПутьВОбратномПорядке)
% где G — уже пройденное расстояние, F = G + h — оценка полного пути.
% Список всё время держится отсортированным по F, поэтому первым
% всегда раскрывается самый перспективный узел.
% ---------------------------------------------------------------------

% a_звезда(Старт, Цель, Путь, Стоимость)
a_звезда(Старт, Цель, Путь, Стоимость) :-
    эвристика(Старт, Цель, H),
    поиск_a([узел(H, 0, [Старт])], Цель, ОбратныйПуть, Стоимость),
    обр(ОбратныйПуть, Путь).

% Цель достигнута: голова открытого списка — путь, начинающийся
% (в обратном порядке) с целевого города. Отсечение фиксирует ответ:
% раз список отсортирован по F, это и есть оптимальное решение.
поиск_a([узел(_, G, [Цель|Пройденные])|_], Цель, [Цель|Пройденные], G) :- !.

% Иначе раскрываем лучший узел: строим всех потомков, добавляем их
% к остатку открытого списка и пересортировываем.
поиск_a([узел(_, G, [Текущий|Пройденные])|Остальные], Цель, Путь, Стоимость) :-
    findall(узел(F1, G1, [Сосед, Текущий|Пройденные]),
            (   смежный(Текущий, Сосед, D),
                \+ принадлежит(Сосед, [Текущий|Пройденные]),
                G1 is G + D,
                эвристика(Сосед, Цель, H1),
                F1 is G1 + H1
            ),
            Потомки),
    присоединить(Остальные, Потомки, Объединённые),
    % sort/4 с ключом 1 сортирует по первому аргументу структуры (F);
    % порядок @=< сохраняет дубликаты, обычный sort/2 их удалил бы.
    sort(1, @=<, Объединённые, Отсортированные),
    поиск_a(Отсортированные, Цель, Путь, Стоимость).

% ---------------------------------------------------------------------
% Для сравнения — поиск вглубь из книги (разд. 7.9, с. 189).
% Находит КАКОЙ-НИБУДЬ путь, а не кратчайший; список Бывали нужен,
% чтобы не зациклиться, возвращаясь в уже посещённый город.
% ---------------------------------------------------------------------

переход(Старт, Цель, Путь) :-
    переход0(Старт, Цель, [], Обратный),
    обр(Обратный, Путь).

переход0(X, X, Бывали, [X|Бывали]).
переход0(X, Y, Бывали, Результат) :-
    следузел(X, [X|Бывали], Z),
    переход0(Z, Y, [X|Бывали], Результат).

следузел(X, Бывали, Y) :-
    смежный(X, Y, _),
    \+ принадлежит(Y, Бывали).

% длина_пути(Путь, Длина) — суммарная протяжённость маршрута.
длина_пути([_], 0) :- !.
длина_пути([X, Y|Хвост], Длина) :-
    смежный(X, Y, D),
    !,
    длина_пути([Y|Хвост], Остаток),
    Длина is D + Остаток.

% проверить_эвристику — убедиться, что оценка нигде не завышает:
% для каждой дороги прямое расстояние должно быть не больше дорожного.
проверить_эвристику :-
    forall(дуга(X, Y, D),
           (   эвристика(X, Y, H),
               (   H =< D
               ->  Вердикт = 'ок'
               ;   Вердикт = 'ЗАВЫШАЕТ!'
               ),
               format('      ~w - ~w~t~32| дорога ~w, прямая ~2f  ~w~n',
                      [X, Y, D, H, Вердикт])
           )).


лр4 :-
    заголовок('ЛР4. Поиск по графу, алгоритм A*'),
    format('  Проверка допустимости эвристики:~n'),
    проверить_эвристику,
    nl,
    format('  Поиск вглубь (вариант книги), дарлингтон -> уэркингтон:~n'),
