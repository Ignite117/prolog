% =====================================================================
%  ЛАБОРАТОРНАЯ РАБОТА № 2
%  Списки в Prolog. Упражнение 3.1 (с. 80)
%
%  Книга (разд. 3.5) строит предикат меньше/2, сравнивающий два слова
%  по алфавиту. Слово переводится в список кодов литер предикатом
%  name/2, после чего списки сравниваются поэлементно по пяти
%  условиям (с. 78):
%    (1) кончилось первое слово, второе продолжается   -> истина
%    (2) очередная литера первого меньше                -> истина
%    (3) литеры совпали — сравнить остатки (рекурсия)
%    (4) кончились оба слова одновременно               -> ЛОЖЬ
%    (5) кончилось второе слово, первое продолжается    -> ложь
%
%  ЗАДАНИЕ упражнения 3.1: добавить ещё одно утверждение так, чтобы
%  предикат был истинен и в случае совпадения слов, то есть получить
%  отношение «меньше или равно по алфавиту». Указание книги —
%  обратить внимание на условие (4).
% =====================================================================

% --- Исходный вариант из книги (строго меньше) ---

% меньше(X, Y) — слово X предшествует слову Y по алфавиту.
% name/2 превращает атом в список кодов литер и обратно:
%   ?- name(алп, X).   X = [1072, 1083, 1087]
меньше(X, Y) :-
    name(X, СписокX),
    name(Y, СписокY),
    меньше_1(СписокX, СписокY).

% Условие (1): первый список пуст, второй — нет.
% Шаблон [_|_] требует непустого списка; просто [_] значило бы
% «список ровно из одного элемента», а это не то же самое.
меньше_1([], [_|_]).
% Условие (2): очередные литеры различны, первая меньше.
меньше_1([X|_], [Y|_]) :- X < Y.
% Условие (3): литеры совпали — сравниваем остатки.
меньше_1([A|X], [B|Y]) :- A =:= B, меньше_1(X, Y).
% Условия (4) и (5) не записываются вовсе: если ни одно утверждение
% не согласуется с базой данных, цель и так окажется ложной.


% --- РЕШЕНИЕ УПРАЖНЕНИЯ 3.1 ---
% Копия предиката с ОДНИМ добавленным утверждением (помечено *).
% Оно описывает условие (4): оба списка кончились одновременно,
% то есть слова совпали. В исходном варианте такая цель проваливалась,
% теперь — успешно завершается.

меньше_равно(X, Y) :-
    name(X, СписокX),
    name(Y, СписокY),
    меньше_равно_1(СписокX, СписокY).

меньше_равно_1([], []).                  % (*) ДОБАВЛЕНО: слова совпали
меньше_равно_1([], [_|_]).                                      % (1)
меньше_равно_1([X|_], [Y|_]) :- X < Y.                          % (2)
меньше_равно_1([A|X], [B|Y]) :- A =:= B, меньше_равно_1(X, Y).  % (3)

% ПОЧЕМУ новое утверждение поставлено первым, а не последним?
% На ответ «истина/ложь» порядок не влияет — утверждения проверяются
% по очереди, пока одно не согласуется. Но при поиске с возвратом
% порядок задаёт порядок выдачи решений, а граничное условие,
% стоящее первым, раньше обрывает рекурсию. Это вопрос стиля,
% а не корректности.
%
% ЗАМЕЧАНИЕ про кириллицу: порядок кодов в Unicode для русских букв
% совпадает с алфавитным (а = 1072, б = 1073, ... я = 1103), поэтому
% предикат работает и для русских слов. Исключение — буква ё
% (код 1105), которая стоит после я. Для латиницы всё корректно:
% a = 97 ... z = 122.


% --- Дополнительные задачи на списки (типовая часть ЛР2) ---

% сумма(Список, Сумма) — сумма элементов числового списка.
сумма([], 0).
сумма([X|Хвост], S) :- сумма(Хвост, S1), S is S1 + X.

% максимум(Список, Max) — наибольший элемент непустого списка.
максимум([X], X) :- !.
максимум([X|Хвост], Max) :-
    максимум(Хвост, MaxХвоста),
    (   X > MaxХвоста
    ->  Max = X
    ;   Max = MaxХвоста
    ).

% удалить(Элемент, Список, Результат) — удалить ВСЕ вхождения.
% Отсечение во втором утверждении не даёт при возврате применить
% третье утверждение к тому же элементу и «сохранить» его.
удалить(_, [], []).
удалить(X, [X|Хвост], Результат) :- !, удалить(X, Хвост, Результат).
удалить(X, [Y|Хвост], [Y|Результат]) :- удалить(X, Хвост, Результат).

% Сортировка слов вставками, использующая меньше_равно/2.
% Показывает, зачем было нужно упражнение 3.1: будь здесь строгое
% меньше/2, одинаковые слова не вставлялись бы в нужное место.
сорт_слова([], []).
сорт_слова([X|Хвост], Отсортированный) :-
    сорт_слова(Хвост, ОтсортХвост),
    вставить(X, ОтсортХвост, Отсортированный).

вставить(X, [], [X]).
вставить(X, [Y|Хвост], [X, Y|Хвост]) :- меньше_равно(X, Y), !.
вставить(X, [Y|Хвост], [Y|Результат]) :- вставить(X, Хвост, Результат).


лр2 :-
    заголовок('ЛР2. Упражнение 3.1 — списки и сравнение слов'),
    format('  Исходный предикат меньше/2 (строго меньше):~n'),
