женщина(александра).
женщина(дагмар).
женщина(луиза).

% отец(X, Y) — X является отцом Y
отец(альберт,  эдуард).
отец(альберт,  алиса).
отец(альберт,  артур).
отец(альберт,  беатриса).
отец(эдуард,   георг).
отец(кристиан, александра).
отец(кристиан, дагмар).

% мать(X, Y) — X является матерью Y
мать(виктория,   эдуард).
мать(виктория,   алиса).
мать(виктория,   артур).
мать(виктория,   беатриса).
мать(александра, георг).
мать(луиза,      александра).
мать(луиза,      дагмар).

% родитель(X, Y) — X является родителем Y.
% Два отдельных утверждения — это ИЛИ (дизъюнкция): родитель — тот,
% кто отец, ИЛИ тот, кто мать. Prolog сначала пробует первое
% утверждение, а при возврате — второе.
родитель(X, Y) :- отец(X, Y).
родитель(X, Y) :- мать(X, Y).

% различны(X, Y) — X и Y не совпадают.
% \== проверяет несовпадение термов. Важно: к моменту вызова оба
% аргумента должны быть конкретизированы, иначе две разные свободные
% переменные дадут «истину» и проверка потеряет смысл.
различны(X, Y) :- X \== Y.


% --- Собственно решение упражнения 1.3 ---

% является_матерью(X) — X является матерью (хоть кого-нибудь).
% '_' — анонимная переменная: нас не интересует, ЧЬЕЙ матерью,
% важно лишь, что подходящий ребёнок существует.
является_матерью(X) :- мать(X, _).

% является_отцом(X) — X является отцом.
является_отцом(X) :- отец(X, _).

% является_сыном(X) — X является сыном.
% Сын — это мужчина, у которого есть родитель.
является_сыном(X) :- мужчина(X), родитель(_, X).

% является_дочерью(X) — симметрично (сверх задания, для полноты).
является_дочерью(X) :- женщина(X), родитель(_, X).

% общие_родители(X, Y) — X и Y имеют общих родителей.
% Переменные M и F сцеплены: ОДНА И ТА ЖЕ M должна быть матерью обоих,
% ОДИН И ТОТ ЖЕ F — отцом обоих. Именно повторное вхождение переменной
% в разных целях и выражает требование «тот же самый».
общие_родители(X, Y) :-
    мать(M, X), мать(M, Y),
    отец(F, X), отец(F, Y).

% является_сестрой(X, Y) — X является сестрой Y.
% Три условия: X — женщина; у X и Y общие родители; X и Y — разные
% люди. Без последней проверки Алиса оказалась бы сестрой самой себе,
% так как общие_родители(алиса, алиса) истинно.
является_сестрой(X, Y) :-
    женщина(X),
    общие_родители(X, Y),
    различны(X, Y).

% является_братом(X, Y) — то же для мужчины.
является_братом(X, Y) :-
    мужчина(X),
    общие_родители(X, Y),
    различны(X, Y).

% дедушка(X, Y) — X является дедушкой Y.
% Цепочка из двух шагов: X — родитель Z, Z — родитель Y.
% Переменная Z нигде не выводится, она лишь связывает два условия.
дедушка(X, Y) :-
    мужчина(X),
    родитель(X, Z),
    родитель(Z, Y).

% бабушка(X, Y) — симметрично.
бабушка(X, Y) :-
    женщина(X),
    родитель(X, Z),
    родитель(Z, Y).

% тётя(X, Y) — правило-образец, приведённое в книге на с. 39.
% ВНИМАНИЕ: здесь не проверяется, что X и Z — разные люди. Если X = Z,
% правило вырождается в «женщина X, являющаяся родителем Y», то есть
% мать ребёнка оказывается его же тётей. В нашей базе данных это видно
% на запросе тётя(X, георг): среди ответов будет александра — его мать.
тётя(X, Y) :-
    женщина(X),
    общие_родители(X, Z),
    родитель(Z, Y).

% Исправленный вариант: тётя — это сестра родителя.
тётя_исправленная(X, Y) :-
    является_сестрой(X, Z),
    родитель(Z, Y).


