% принадлежит(Элемент, Список) — Элемент входит в Список.
% Первое утверждение — граничное условие: элемент совпал с головой.
% Второе — рекурсия: ищем в хвосте. Книга, разд. 3.3.
принадлежит(X, [X|_]).
принадлежит(X, [_|Хвост]) :- принадлежит(X, Хвост).

% присоединить(Список1, Список2, Результат) — конкатенация.
% Граничное условие: пустой список + L = L.
% Рекурсия: голова первого списка переносится в голову результата,
% причём X в заголовке правила встречается дважды — это и «сшивает»
% вход с выходом. Книга, разд. 3.6.
присоединить([], L, L).
присоединить([X|L1], L2, [X|L3]) :- присоединить(L1, L2, L3).

% обр(Список, Обращённый) — переворот списка.
% Используется накопитель (второй аргумент обр/3): элементы по одному
% снимаются с головы входа и «надеваются» на голову накопителя,
% отчего порядок и переворачивается. Это работает за O(n), тогда как
% наивный вариант через присоединить — за O(n^2).
обр(Список, Обращённый) :- обр(Список, [], Обращённый).

обр([], Накопитель, Накопитель).
обр([X|Хвост], Накопитель, Результат) :- обр(Хвост, [X|Накопитель], Результат).

% длина(Список, N) — число элементов.
длина([], 0).
длина([_|Хвост], N) :- длина(Хвост, M), N is M + 1.

% первые(N, Список, Начало) — взять не более N первых элементов.
первые(0, _, []) :- !.
первые(_, [], []) :- !.
первые(N, [X|Хвост], [X|Начало]) :-
    M is N - 1,
    первые(M, Хвост, Начало).


% склонение(N, [Форма1, Форма2, Форма5], Слово) — выбрать русскую форму
% существительного по числу: 1 диск, 2 диска, 5 дисков.
% Правило обычное: смотрим на последнюю цифру, но числа от 11 до 14
% (точнее, остаток от деления на 100) — исключение, у них форма «пять».
склонение(N, [Один, Два, Много], Слово) :-
    Сотня   is N mod 100,
    Десяток is N mod 10,
    (   Сотня >= 11, Сотня =< 14   ->  Слово = Много
    ;   Десяток =:= 1              ->  Слово = Один
    ;   Десяток >= 2, Десяток =< 4 ->  Слово = Два
    ;                                  Слово = Много
    ).


% --- Служебные предикаты для печати результатов ---

% Напечатать решения цели, убрав повторы.
% findall/3 собирает ВСЕ решения, включая одинаковые: если к одному
% и тому же ответу ведут разные пути вывода, он появится столько раз,
% сколько путей нашлось. sort/2 оставляет только различные значения,
% а исходное количество печатается отдельной строкой — это тот самый
% эффект, про который спрашивает упражнение 1.2 книги.
показать_решения(Заголовок, Цель, Шаблон) :-
    format('  ~w:~n', [Заголовок]),
    findall(Шаблон, Цель, Все),
    (   Все == []
    ->  format('      (нет решений)~n')
    ;   sort(Все, Различные),
        forall(принадлежит(X, Различные), format('      ~w~n', [X])),
        длина(Все, Всего),
        длина(Различные, Разных),
        (   Всего > Разных
        ->  format('      (путей вывода ~w, различных ответов ~w)~n',
                   [Всего, Разных])
        ;   true
        )
    ),
    nl.

% Напечатать «да»/«нет» для цели.
% \+ \+ Цель проверяет согласуемость, не оставляя конкретизаций.
проверить(Подпись, Цель) :-
    (   \+ \+ call(Цель)
    ->  Ответ = 'да'
    ;   Ответ = 'нет'
    ),
    format('      ~w~t~52| ~w~n', [Подпись, Ответ]).

заголовок(Текст) :-
    nl,
    format('======================================================~n'),
    format(' ~w~n', [Текст]),
    format('======================================================~n').


