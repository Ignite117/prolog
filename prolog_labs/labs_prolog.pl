    проверить('меньше_равно(картина, картина)',    меньше_равно(картина, картина)),
    проверить('меньше_равно(пар, паровоз)',        меньше_равно(пар, паровоз)),
    проверить('меньше_равно(алфавитный, алфавит)', меньше_равно(алфавитный, алфавит)),
    nl,
    format('  Прочие операции над списками:~n'),
    сорт_слова([слон, арбуз, картина, арбуз, букварь], Отсорт),
