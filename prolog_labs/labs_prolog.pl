показать_трансляцию(Правило) :-
    транслировать(Правило, Утверждение),
    % Свободные переменные печатаются как _4782 и мешают читать.
    % copy_term/2 делает копию, чтобы не испортить исходный терм,
    % numbervars/3 заменяет в ней переменные на '$VAR'(0), '$VAR'(1)...,
    % а ~W с опцией numbervars(true) печатает их как A, B, C.
    copy_term(Правило-Утверждение, КопияП-КопияУ),
    numbervars(КопияП-КопияУ, 0, _),
    format('      ~W~n',       [КопияП, [numbervars(true)]]),
    format('        =>  ~W~n', [КопияУ, [numbervars(true)]]).


% =====================================================================
%  ЛАБОРАТОРНАЯ РАБОТА № 6
%  Реализация клиента TCP/IP
%
%  В книге Клоксина и Меллиша этого нет: работа с сетью не входит
%  в стандарт Пролога. Здесь используется библиотека SWI-Prolog
%  library(socket).
%
%  Схема клиента всегда одна и та же:
%    1) установить соединение   — tcp_connect/3
%    2) писать и читать поток   — format/3, read_line_to_string/2
%    3) закрыть соединение      — close/1
%  setup_call_cleanup/3 гарантирует, что шаг 3 выполнится даже при
%  ошибке на шаге 2, — иначе сокет остался бы висеть открытым.
% =====================================================================

% --- Эхо-сервер, чтобы лабораторную можно было проверить локально ---

% эхо_сервер(Порт) — принимает соединения и возвращает присланную
% строку обратно с префиксом. Вызов блокирующий, поэтому запускать
% его следует в отдельном потоке (см. запустить_сервер/1).
эхо_сервер(Порт) :-
    tcp_socket(Сокет),
    tcp_setopt(Сокет, reuseaddr),
    tcp_bind(Сокет, Порт),
    tcp_listen(Сокет, 5),
    format('      [сервер] слушаю порт ~w~n', [Порт]),
    эхо_цикл(Сокет).

эхо_цикл(Сокет) :-
    tcp_accept(Сокет, Соединение, _Адрес),
    tcp_open_socket(Соединение, Поток),
    % ОБЯЗАТЕЛЬНО: сокет открывается в однобайтовой кодировке, и любая
    % кириллица вызывает ошибку «Encoding cannot represent character».
    % Обе стороны должны договориться об одной кодировке — ставим UTF-8.
    set_stream(Поток, encoding(utf8)),
    эхо_обслужить(Поток),
    close(Поток),
    эхо_цикл(Сокет).

эхо_обслужить(Поток) :-
    read_line_to_string(Поток, Строка),
    (   Строка == end_of_file
    ->  true
    ;   format(Поток, 'эхо: ~w~n', [Строка]),
        flush_output(Поток),
        эхо_обслужить(Поток)
    ).

% запустить_сервер(Порт) — поднять сервер в фоновом потоке.
% detached(true) означает, что поток не нужно «присоединять»
% предикатом thread_join/2: он завершится сам.
запустить_сервер(Порт) :-
    thread_create(эхо_сервер(Порт), _, [detached(true)]).


% --- Собственно клиент ---

% эхо_клиент(Хост, Порт, Сообщение) — отправить строку, прочитать ответ.
эхо_клиент(Хост, Порт, Сообщение) :-
    setup_call_cleanup(
        tcp_connect(Хост:Порт, Поток, []),
        (   set_stream(Поток, encoding(utf8)),   % см. примечание в эхо_цикл/1
            format(Поток, '~w~n', [Сообщение]),
            flush_output(Поток),
            read_line_to_string(Поток, Ответ),
            format('      [клиент] отправлено: ~w~n', [Сообщение]),
            format('      [клиент] получено:   ~w~n', [Ответ])
        ),
        close(Поток)
    ).

% http_клиент(Хост, Путь) — минимальный HTTP-клиент поверх того же
% сокета: показывает, что протокол прикладного уровня — это просто
% текст, который пишется в тот же поток.
% Connection: close просит сервер закрыть соединение после ответа,
% иначе чтение до конца потока никогда не завершится.
http_клиент(Хост, Путь) :-
    setup_call_cleanup(
        tcp_connect(Хост:80, Поток, []),
        (   format(Поток,
                   "GET ~w HTTP/1.1\r\nHost: ~w\r\nConnection: close\r\n\r\n",
                   [Путь, Хост]),
            flush_output(Поток),
            читать_заголовки(Поток)
        ),
        close(Поток)
    ).

% Печатает только заголовки ответа — до первой пустой строки.
читать_заголовки(Поток) :-
    read_line_to_string(Поток, Строка),
    (   (Строка == end_of_file ; Строка == "")
    ->  true
    ;   format('      ~w~n', [Строка]),
        читать_заголовки(Поток)
    ).


