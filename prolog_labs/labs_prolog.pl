% маршрут(Откуда, Куда) — найти и напечатать кратчайший путь.
маршрут(Откуда, Куда) :-
    a_звезда(Откуда, Куда, Путь, Цена),
    склонение(Цена, [миля, мили, миль], СловоМ),
    format('      кратчайший: ~w~n', [Путь]),
    format('      длина:      ~w ~w~n', [Цена, СловоМ]).


% =====================================================================
%  ЛАБОРАТОРНАЯ РАБОТА № 5
%  Грамматики DCG в SWI-Prolog. Предикат phrase.
%  Глава 9, упражнение 9.1 (с. 246-247)
%
%  Грамматическое правило
%      предложение --> группа_существительного, группа_глагола.
%  транслируется системой в обычное утверждение Пролога
%      предложение(S0, S) :- группа_существительного(S0, S1),
%                            группа_глагола(S1, S).
%  Два добавленных аргумента — это обрабатываемый список слов и
%  список, оставшийся после обработки (приём «разностные списки»).
%
%  ЗАДАНИЕ упражнения 9.1: написать процедуру translate(X, Y),
%  которая по грамматическому правилу X строит соответствующее
%  утверждение Пролога Y. Книга честно предупреждает, что упражнение
%  трудное, — зато, выполнив его, понимаешь, что такое трансляция.
% =====================================================================

% --- Простая грамматика из книги (разд. 9.3) ---

предложение --> группа_существительного, группа_глагола.

группа_существительного --> определитель, существительное.

группа_глагола --> глагол.
группа_глагола --> глагол, группа_существительного.

определитель --> [the].
определитель --> [a].

существительное --> [man].
существительное --> [apple].
существительное --> [song].

глагол --> [eats].
глагол --> [sings].

% Проверка: phrase(Класс, Список) истинно, если Список является
% допустимым словосочетанием типа Класс (книга, с. 246):
%   ?- phrase(предложение, [the, man, eats, the, apple]).
%   true.
% Благодаря механизму возврата та же грамматика умеет ПОРОЖДАТЬ
% предложения, а не только проверять их:
%   ?- phrase(предложение, X).


% --- Грамматика с деревом разбора (разд. 9.4) ---
% У нетерминалов появляется дополнительный аргумент, в котором
% собирается структура разбора. Это другие предикаты: предложение//1,
% а не предложение//0, — в Прологе имя и арность вместе задают предикат.

предложение(предложение(ГС, ГГ)) -->
    группа_существительного(ГС), группа_глагола(ГГ).

группа_существительного(гс(О, С)) --> определитель(О), существительное(С).

группа_глагола(гг(Г))     --> глагол(Г).
группа_глагола(гг(Г, ГС)) --> глагол(Г), группа_существительного(ГС).

определитель(опр(the)) --> [the].
определитель(опр(a))   --> [a].

существительное(сущ(man))   --> [man].
существительное(сущ(apple)) --> [apple].
существительное(сущ(song))  --> [song].

глагол(гл(eats))  --> [eats].
глагол(гл(sings)) --> [sings].


% --- РЕШЕНИЕ УПРАЖНЕНИЯ 9.1 ---
% транслировать(ГрамматическоеПравило, УтверждениеПролога)
%
% Идея: к заголовку правила добавляются два аргумента S0 и S,
% а тело «протягивается» цепочкой промежуточных переменных:
% первый нетерминал получает (S0, S1), второй — (S1, S2) и так далее,
% последний — (Sn, S). Терминалы же просто откусывают слова от списка.

транслировать((Голова --> Тело), (НовГолова :- НовТело)) :-
    дополнить(Голова, S0, S, НовГолова),
    тело_правила(Тело, S0, S, НовТело).

% дополнить(Терм, S0, S, НовыйТерм) — приписать терму два аргумента.
% =.. («юнив») разбирает терм в список [функтор | аргументы]
% и собирает обратно (книга, разд. 6.5):
%   предложение =.. [предложение]  ->  [предложение, S0, S]
%                                  ->  предложение(S0, S)
дополнить(Терм, S0, S, НовыйТерм) :-
    Терм =.. Список,
    присоединить(Список, [S0, S], НовыйСписок),
    НовыйТерм =.. НовыйСписок.

% Конъюнкция: протягиваем цепочку через промежуточную переменную S1.
тело_правила((A, B), S0, S, (НA, НB)) :- !,
    тело_правила(A, S0, S1, НA),
    тело_правила(B, S1, S,  НB).
% Дизъюнкция: обе ветви обрабатывают один и тот же участок списка.
тело_правила((A ; B), S0, S, (НA ; НB)) :- !,
    тело_правила(A, S0, S, НA),
    тело_правила(B, S0, S, НB).
% Фигурные скобки {Цель} — обычная цель Пролога, список не трогает.
тело_правила({Цель}, S0, S, (Цель, S0 = S)) :- !.
% Пустой список — ничего не откусываем.
тело_правила([], S0, S, (S0 = S)) :- !.
% Отсечение внутри грамматического правила.
тело_правила(!, S0, S, (!, S0 = S)) :- !.
% Список терминалов: эти слова должны стоять в начале списка.
%   [the]  ->  присоединить([the], S, S0),  то есть S0 = [the|S]
тело_правила(Список, S0, S, присоединить(Список, S, S0)) :-
    is_list(Список), !.
% Всё остальное — нетерминал, ему дописываются два аргумента.
тело_правила(Нетерминал, S0, S, Цель) :-
    дополнить(Нетерминал, S0, S, Цель).


